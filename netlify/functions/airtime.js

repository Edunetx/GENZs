const fetch = require("node-fetch");

exports.handler = async (event, context) => {
  try {
    const body = JSON.parse(event.body);

    const payload = new URLSearchParams(body);

    const response = await fetch("https://zendek.com.ng/autobiz_vending_index.php", {
      method: "POST",
      headers: {
        "Content-Type": "application/x-www-form-urlencoded",
        "Authorization": `Bearer ${process.env.ZENDEK_API_KEY}`
      },
      body: payload
    });

    const text = await response.text();

    let data;
    try {
      data = JSON.parse(text);
    } catch {
      return {
        statusCode: 500,
        body: JSON.stringify({ error: "Invalid response from Zendek", raw: text })
      };
    }

    return {
      statusCode: 200,
      body: JSON.stringify(data)
    };
  } catch (err) {
    console.error(err);
    return {
      statusCode: 500,
      body: JSON.stringify({ error: "Error connecting to Zendek" })
    };
  }
};